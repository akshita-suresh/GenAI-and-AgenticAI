    for d in dirs:
        if d.lower() in ("cats", "dogs"):
            src = os.path.join(root, d)
            rel = os.path.relpath(src, src_path).lower()
            split = "train" if "train" in rel else "validation"
            n = N_TRAIN if split == "train" else N_VAL
            dst = f"{BASE}/{split}/{d.lower()}"
            os.makedirs(dst, exist_ok=True)
            imgs = [f for f in os.listdir(src)
                    if f.lower().endswith((".jpg", ".jpeg", ".png"))]
            random.shuffle(imgs)
            for f in imgs[:n]:
                shutil.copy(os.path.join(src, f), dst)

