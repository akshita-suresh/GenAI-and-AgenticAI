def merge_dicts(a, b):
    return {**(a or {}), **(b or {})}

class FailoverState(TypedDict):
    question: str
    down: list
    health: str
    results: Annotated[dict, merge_dicts]
    n_ok: int
    scores: dict
    judge_notes: str
    winner: int
    final_reasoning: str
    final_answer: str
    report: str
    email_to: str        # NEW: recipient (empty = don't send)
    email_status: str    # NEW: result of sending

ANSWER_PROMPT = """You are an expert answering a question.
Use chain-of-thought: think step by step and write each step as a numbered line.
Format your reply EXACTLY like this:
REASONING:
1. ...
2. ...
FINAL ANSWER:
<clear, complete, concise answer>"""

JUDGE_PROMPT = """You are an impartial judge comparing several answers to the same question.
Think step by step:
1. Work out what the correct answer should be yourself.
2. Check every reasoning step of each answer for mistakes.
3. Compare on correctness first, then completeness, then clarity.
Do NOT favour an answer because of its position or length.
Write a short comparison, then end with one score line per answer and a notes line, exactly:
SCORE_1: <integer 1-10>
SCORE_2: <integer 1-10>
(one SCORE line for every answer given)
NOTES: <one sentence on the biggest difference>"""

def health_node(state: FailoverState):
    """Ping every LLM. Anything that errors (or is in FORCE_DOWN) is marked DOWN."""
    down, lines = [], []
    for n, name in MODELS.items():
        if n in FORCE_DOWN:
            down.append(n); lines.append(f"LLM {n} ({name}): DOWN (forced for demo)"); continue
        try:
            ask(LLMS[n], "Reply with the single word OK.", "ping")
            lines.append(f"LLM {n} ({name}): UP")
        except Exception as e:
            down.append(n); lines.append(f"LLM {n} ({name}): DOWN ({type(e).__name__})")
    return {"down": down, "health": "\n".join(lines), "results": {}}

def make_llm_node(n):
    """Factory: one node per LLM. Skips if down, and survives runtime errors."""
    def llm_node(state: FailoverState):
        if n in state["down"]:
            return {"results": {n: {"ok": False, "note": "skipped (down)"}}}
        start = time.time()
        try:
            text = ask(LLMS[n], ANSWER_PROMPT, f"Question: {state['question']}")
            reasoning, _, answer = text.partition("FINAL ANSWER:")
            return {"results": {n: {"ok": True,
                                    "reasoning": reasoning.replace("REASONING:", "").strip(),
                                    "answer": answer.strip() or text,
                                    "time": round(time.time() - start, 2)}}}
        except Exception as e:
            return {"results": {n: {"ok": False, "note": f"failed while answering ({type(e).__name__})"}}}
    return llm_node

def collect_node(state: FailoverState):
    """Join point: counts how many LLMs produced a usable answer."""
    return {"n_ok": sum(1 for r in state["results"].values() if r["ok"])}

def judge_node(state: FailoverState):
    ok_ids = [n for n, r in state["results"].items() if r["ok"]]
    order = ok_ids[:]; random.shuffle(order)            # random order avoids position bias
    user = f"Question: {state['question']}\n\n"
    for i, n in enumerate(order, 1):
        r = state["results"][n]
        user += f"=== Answer {i} ===\nReasoning:\n{r['reasoning']}\nFinal answer:\n{r['answer']}\n\n"

    judge_llm = LLMS[next(n for n in [1, 3, 2] if n in ok_ids)]   # most reliable working LLM judges
    text = ask(judge_llm, JUDGE_PROMPT, user)

    scores = {}
    for i, n in enumerate(order, 1):
        m = re.search(rf"SCORE_{i}:\s*(\d+)", text)
        scores[n] = min(int(m.group(1)), 10) if m else 5
    notes = re.search(r"NOTES:\s*(.+)", text)
    best = max(scores.values())
    winner = next(n for n in [1, 3, 2] if scores.get(n) == best)   # ties go to the most reliable LLM
    r = state["results"][winner]
    return {"scores": scores, "winner": winner,
            "judge_notes": notes.group(1).strip() if notes else "No notes.",
            "final_reasoning": r["reasoning"], "final_answer": r["answer"]}

def finalize_node(state: FailoverState):
    winner, scores = state["winner"], state.get("scores") or {}
    reasoning, answer = state.get("final_reasoning", ""), state.get("final_answer", "")
    note = "Judge compared the working LLMs." if scores else "Only one LLM answered, so no comparison was needed."
    if not winner:                                       # single-answer path
        winner = next(n for n, r in state["results"].items() if r["ok"])
        r = state["results"][winner]
        reasoning, answer = r["reasoning"], r["answer"]
    lines = []
    for n, name in MODELS.items():
        r = state["results"][n]
        detail = (f"answered in {r['time']}s" + (f", score {scores[n]}/10" if n in scores else "")
                  if r["ok"] else r["note"])
        lines.append(f"  LLM {n} ({name}): {detail}")
    report = (f"--- Health check ---\n{state['health']}\n\n"
              f"--- Results ---\n" + "\n".join(lines) + "\n\n"
              f"{note} {state.get('judge_notes', '')}\n"
              f"WINNER: LLM {winner} ({MODELS[winner]})\n\n"
              f"--- Reasoning ---\n{reasoning}\n\n=== BEST ANSWER ===\n{answer}")
    return {"winner": winner, "final_reasoning": reasoning, "final_answer": answer, "report": report}

def fail_node(state: FailoverState):
    return {"report": f"--- Health check ---\n{state['health']}\n\n"
                      "No LLM could answer right now. Check your API key, model names and rate limits, then try again."}

def email_node(state: FailoverState):
    """Send the final report to Gmail. A failure here never crashes the workflow."""
    try:
        subject = f"LLM Arena result: {state['question'][:60]}"
        body = (f"Question:\n{state['question']}\n\n"
                f"{'=' * 50}\n{state['report']}\n\n"
                f"-- Sent by your LangGraph Failover Arena")
        send_gmail(state["email_to"], subject, body)
        return {"email_status": f"Sent to {state['email_to']}"}
    except Exception as e:
        return {"email_status": f"Email failed ({type(e).__name__}: {e})"}

def route_after_finalize(state: FailoverState) -> str:
    """Send an email only if a recipient address is set."""
    return "email" if state.get("email_to") else END

def route_after_collect(state: FailoverState) -> str:
    """0 answers -> fail.  1 answer -> finalize directly.  2+ answers -> judge them."""
    if state["n_ok"] == 0:
        return "fail"
    if state["n_ok"] == 1:
        return "finalize"
    return "judge"

from langgraph.graph import StateGraph, START, END

b = StateGraph(FailoverState)

b.add_node("health_check", health_node)
b.add_node("llm_1", make_llm_node(1))
b.add_node("llm_2", make_llm_node(2))
b.add_node("llm_3", make_llm_node(3))
b.add_node("collect", collect_node)
b.add_node("judge", judge_node)
b.add_node("finalize", finalize_node)
b.add_node("email", email_node)
b.add_node("fail", fail_node)

b.add_edge(START, "health_check")
for n in ["llm_1", "llm_2", "llm_3"]:
    b.add_edge("health_check", n)
b.add_edge(["llm_1", "llm_2", "llm_3"], "collect")
b.add_conditional_edges("collect", route_after_collect, ["fail", "finalize", "judge"])
b.add_edge("judge", "finalize")
b.add_conditional_edges("finalize", route_after_finalize, ["email", END])   # NEW route
b.add_edge("email", END)
b.add_edge("fail", END)

failover = b.compile()

