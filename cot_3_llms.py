def salvage(err):
    """Recover the text from a gpt-oss 'tool_use_failed' error."""
    m = re.search(r'"arguments":\s*"?(.*)', str(err), re.S)
    if not m:
        return None
    text = m.group(1).replace("\\n", "\n").replace('\\"', '"')
    return text.rstrip("\"'} \n") or None

def clean(text):
    """Remove <think>...</think> blocks that some reasoning models add."""
    return re.sub(r"<think>.*?</think>", "", text, flags=re.S).strip()

def ask(llm, system_prompt, user_prompt):
    msgs = [SystemMessage(content=system_prompt), HumanMessage(content=user_prompt)]
    try:
        return clean(llm.invoke(msgs).content)
    except BadRequestError as e:
        text = salvage(e)
        if text:
            return clean(text)
        raise

