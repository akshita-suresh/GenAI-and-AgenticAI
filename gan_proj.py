BATCH = 256
EPOCHS = 15

train_ds = (tf.data.Dataset.from_tensor_slices(x_train_n)
            .shuffle(60000).batch(BATCH, drop_remainder=True)
            .prefetch(tf.data.AUTOTUNE))

bce = tf.keras.losses.BinaryCrossentropy(from_logits=True)
g_opt = tf.keras.optimizers.Adam(2e-4, beta_1=0.5)
d_opt = tf.keras.optimizers.Adam(2e-4, beta_1=0.5)

@tf.function
def train_step(real_images):
    noise = tf.random.normal([BATCH, NOISE])
    with tf.GradientTape() as g_tape, tf.GradientTape() as d_tape:
        fake_images = generator(noise, training=True)
        real_out = discriminator(real_images, training=True)
        fake_out = discriminator(fake_images, training=True)

        g_loss = bce(tf.ones_like(fake_out), fake_out)
        # label smoothing (0.9) keeps the discriminator from becoming overconfident
        d_loss = (bce(tf.ones_like(real_out) * 0.9, real_out) +
                  bce(tf.zeros_like(fake_out), fake_out))

    g_grads = g_tape.gradient(g_loss, generator.trainable_variables)
    d_grads = d_tape.gradient(d_loss, discriminator.trainable_variables)
    g_opt.apply_gradients(zip(g_grads, generator.trainable_variables))
    d_opt.apply_gradients(zip(d_grads, discriminator.trainable_variables))

    real_acc = tf.reduce_mean(tf.cast(real_out > 0, tf.float32))
    fake_acc = tf.reduce_mean(tf.cast(fake_out < 0, tf.float32))
    return g_loss, d_loss, real_acc, fake_acc

import time

fixed_noise = tf.random.normal([16, NOISE], seed=7)   # same noise every epoch to track progress
snap_epochs = [1, 3, 5, 10, 15]
snapshots = {}
hist = {"g_loss": [], "d_loss": [], "real_acc": [], "fake_acc": []}

for epoch in range(1, EPOCHS + 1):
    t0 = time.time()
    m = []
    for batch in train_ds:
        m.append([v.numpy() for v in train_step(batch)])
    m = np.mean(m, axis=0)
    for k, v in zip(hist.keys(), m):
        hist[k].append(float(v))
    if epoch in snap_epochs:
        snapshots[epoch] = generator(fixed_noise, training=False).numpy()
    print(f"Epoch {epoch:2d}/{EPOCHS} | G loss {m[0]:.3f} | D loss {m[1]:.3f} | "
          f"D acc real {m[2]:.0%} fake {m[3]:.0%} | {time.time() - t0:.1f}s")

