def salvage(err):
    """Recover the model's text from a gpt-oss 'tool_use_failed' error."""
    m = re.search(r'"arguments":\s*"?(.*)', str(err), re.S)
    if not m:
        return None
    text = m.group(1).replace("\\n", "\n").replace('\\"', '"')
    return text.rstrip("\"'} \n") or None

def ask(llm, system_prompt, user_prompt):
    msgs = [SystemMessage(content=system_prompt), HumanMessage(content=user_prompt)]
    try:
        return llm.invoke(msgs).content.strip()
    except BadRequestError as e:
        text = salvage(e)
        if text:
            return text.strip()
        return llm.invoke(msgs).content.strip()   # one retry

