class ArenaState(TypedDict):
    question: str
    task_type: str        # math | coding | factual | reasoning | creative
    criteria: str         # what a good answer must contain (from analyze node)
    # Contender A
    reasoning_a: str
    answer_a: str
    time_a: float
    # Contender B
    reasoning_b: str
    answer_b: str
    time_b: float
    # Judge
    score_a: int
    score_b: int
    judge_notes: str
    winner: str           # A | B | MERGED
    # Output
    final_reasoning: str
    final_answer: str
    report: str

ANALYZE_PROMPT = """You are a question analyst for an LLM comparison app.
Think step by step:
1. Restate what is being asked.
2. Decide the task type: math, coding, factual, reasoning or creative.
3. List 3 short criteria a really good answer must meet.
Write your steps briefly, then end with exactly these two lines:
TASK_TYPE: <one word>
CRITERIA: <criterion 1>; <criterion 2>; <criterion 3>"""

CONTENDER_PROMPT = """You are an expert answering a question. Evaluation criteria for a good answer: {criteria}
Use chain-of-thought: think step by step, writing each step as a numbered line.
Format your reply EXACTLY like this:
REASONING:
1. ...
2. ...
FINAL ANSWER:
<clear, complete, concise answer>"""

JUDGE_PROMPT = """You are an impartial judge comparing two answers to the same question.
Criteria: {criteria}
Think step by step:
1. Work out what the correct answer should be yourself.
2. Check every reasoning step of Answer 1 for mistakes.
3. Check every reasoning step of Answer 2 for mistakes.
4. Compare on correctness first, then completeness, then clarity.
Do NOT favour an answer because of its position or length.
Write a short comparison, then end with exactly these three lines:
SCORE_1: <integer 1-10>
SCORE_2: <integer 1-10>
NOTES: <one sentence on the biggest difference>"""

MERGE_PROMPT = """Two answers to the same question scored almost equally.
Think step by step:
1. List what Answer 1 does well and where it is weak.
2. List what Answer 2 does well and where it is weak.
3. Build one improved answer that keeps the strengths and fixes the weaknesses.
Format your reply EXACTLY like this:
REASONING:
1. ...
FINAL ANSWER:
<the improved answer>"""

def parse_sections(text):
    reasoning, _, answer = text.partition("FINAL ANSWER:")
    return reasoning.replace("REASONING:", "").strip(), (answer.strip() or text)

def analyze_node(state: ArenaState):
    text = ask(llm_a, ANALYZE_PROMPT, state["question"])
    t = re.search(r"TASK_TYPE:\s*(\w+)", text, re.I)
    c = re.search(r"CRITERIA:\s*(.+)", text, re.I)
    return {"task_type": t.group(1).lower() if t else "reasoning",
            "criteria": c.group(1).strip() if c else "correct; complete; clear"}

def make_contender(llm, tag):
    """Factory: builds one contender node. Both run in parallel and write to different state keys."""
    def contender_node(state: ArenaState):
        start = time.time()
        text = ask(llm, CONTENDER_PROMPT.format(criteria=state["criteria"]),
                   f"Question: {state['question']}")
        reasoning, answer = parse_sections(text)
        return {f"reasoning_{tag}": reasoning, f"answer_{tag}": answer,
                f"time_{tag}": round(time.time() - start, 2)}
    return contender_node

model_a_node = make_contender(llm_a, "a")
model_b_node = make_contender(llm_b, "b")

def judge_node(state: ArenaState):
    # Show the answers in random order to avoid position bias
    a_first = random.random() < 0.5
    first = ("A", state["reasoning_a"], state["answer_a"]) if a_first else ("B", state["reasoning_b"], state["answer_b"])
    second = ("B", state["reasoning_b"], state["answer_b"]) if a_first else ("A", state["reasoning_a"], state["answer_a"])

    user = (f"Question: {state['question']}\n\n"
            f"=== Answer 1 ===\nReasoning:\n{first[1]}\nFinal answer:\n{first[2]}\n\n"
            f"=== Answer 2 ===\nReasoning:\n{second[1]}\nFinal answer:\n{second[2]}")
    text = ask(llm_a, JUDGE_PROMPT.format(criteria=state["criteria"]), user)

    s1 = re.search(r"SCORE_1:\s*(\d+)", text)
    s2 = re.search(r"SCORE_2:\s*(\d+)", text)
    n = re.search(r"NOTES:\s*(.+)", text)
    score1 = min(int(s1.group(1)), 10) if s1 else 5
    score2 = min(int(s2.group(1)), 10) if s2 else 5

    # Map the scores back to A and B
    score_a, score_b = (score1, score2) if first[0] == "A" else (score2, score1)
    update = {"score_a": score_a, "score_b": score_b,
              "judge_notes": n.group(1).strip() if n else "No notes."}

    if abs(score_a - score_b) >= 2:          # clear winner: keep it now
        w = "A" if score_a > score_b else "B"
        update.update({"winner": w,
                       "final_reasoning": state[f"reasoning_{w.lower()}"],
                       "final_answer": state[f"answer_{w.lower()}"]})
    return update

def merge_node(state: ArenaState):
    user = (f"Question: {state['question']}\n\n"
            f"=== Answer 1 ===\n{state['reasoning_a']}\n{state['answer_a']}\n\n"
            f"=== Answer 2 ===\n{state['reasoning_b']}\n{state['answer_b']}\n\n"
            f"Judge's note: {state['judge_notes']}")
    text = ask(llm_a, MERGE_PROMPT, user)
    reasoning, answer = parse_sections(text)
    return {"winner": "MERGED", "final_reasoning": reasoning, "final_answer": answer}

def finalize_node(state: ArenaState):
    who = {"A": f"Model A ({MODEL_A})", "B": f"Model B ({MODEL_B})",
           "MERGED": "Merged answer (scores were too close)"}[state["winner"]]
    report = (f"Task type : {state['task_type']}\n"
              f"Criteria  : {state['criteria']}\n\n"
              f"Model A ({MODEL_A}): score {state['score_a']}/10, {state['time_a']}s\n"
              f"Model B ({MODEL_B}): score {state['score_b']}/10, {state['time_b']}s\n"
              f"Judge says: {state['judge_notes']}\n\n"
              f"WINNER: {who}\n\n"
              f"--- Reasoning ---\n{state['final_reasoning']}\n\n"
              f"=== BEST ANSWER ===\n{state['final_answer']}")
    return {"report": report}

def route_after_judge(state: ArenaState) -> str:
    """Clear winner (score gap >= 2) -> finalize. Too close to call -> merge both answers first."""
    if abs(state["score_a"] - state["score_b"]) >= 2:
        return "finalize"
    return "merge"

from langgraph.graph import StateGraph, START, END

builder = StateGraph(ArenaState)

builder.add_node("analyze", analyze_node)
builder.add_node("model_a", model_a_node)
builder.add_node("model_b", model_b_node)
builder.add_node("judge", judge_node)
builder.add_node("merge", merge_node)
builder.add_node("finalize", finalize_node)

builder.add_edge(START, "analyze")
builder.add_edge("analyze", "model_a")            # fan-out: both run in parallel
builder.add_edge("analyze", "model_b")
builder.add_edge(["model_a", "model_b"], "judge")  # join: judge waits for both
builder.add_conditional_edges("judge", route_after_judge, ["merge", "finalize"])
builder.add_edge("merge", "finalize")
builder.add_edge("finalize", END)

arena = builder.compile()

