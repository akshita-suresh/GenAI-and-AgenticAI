import matplotlib.pyplot as plt

def run_arena(question: str):
    state = {"question": question, "task_type": "", "criteria": "",
             "reasoning_a": "", "answer_a": "", "time_a": 0.0,
             "reasoning_b": "", "answer_b": "", "time_b": 0.0,
             "score_a": 0, "score_b": 0, "judge_notes": "", "winner": "",
             "final_reasoning": "", "final_answer": "", "report": ""}
    print("Workflow trace:")
    for step in arena.stream(state, stream_mode="updates"):
        for node, update in step.items():
            extra = ""
            if node == "analyze": extra = f" -> {update['task_type']}"
            if node == "judge":   extra = f" -> A={update['score_a']}  B={update['score_b']}"
            print(f"  ➡ {node}{extra}")
            state.update(update)
    print("\n" + "=" * 60)
    print(state["report"])

    # Comparison chart
    fig, ax = plt.subplots(1, 2, figsize=(11, 3.8))
    labels = [f"A\n{MODEL_A}", f"B\n{MODEL_B}"]
    bars = ax[0].bar(labels, [state["score_a"], state["score_b"]], color=["tab:blue", "tab:orange"])
    ax[0].set_ylim(0, 10.5); ax[0].set_title("Judge score (out of 10)")
    for b, v in zip(bars, [state["score_a"], state["score_b"]]):
        ax[0].text(b.get_x() + b.get_width() / 2, v + 0.2, v, ha="center")
    bars = ax[1].bar(labels, [state["time_a"], state["time_b"]], color=["tab:blue", "tab:orange"])
    ax[1].set_title("Response time (seconds)")
    for b, v in zip(bars, [state["time_a"], state["time_b"]]):
        ax[1].text(b.get_x() + b.get_width() / 2, v + 0.05, f"{v}s", ha="center")
    plt.tight_layout(); plt.show()
    return state

